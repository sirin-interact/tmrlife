export function isLegalSlug(value: string | undefined): value is LegalSlug {
  return value !== undefined && Object.hasOwn(LEGAL_DOCUMENTS, value);
}

export function legalPath(slug: LegalSlug, sectionId?: string): string {
  return sectionId === undefined ? `/legal/${slug}` : `/legal/${slug}#${sectionId}`;
}
