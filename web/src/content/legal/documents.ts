/**
 * 앱 안에서 읽는 약관과 개인정보 처리방침.
 *
 * !! 초안이다. 법무 검토를 거친 문구가 아니다(LEGAL_DOCUMENTS_ARE_DRAFT). !!
 * 가입 화면의 동의는 이 글을 보고 받는다. 그래서 글을 고치면 반드시 판(version)을 그날의 날짜로 올리고,
 * 서버가 알려주는 동의의 판도 같은 값으로 올린다. 두 값이 다르면 가입 화면은 가입을 받지 않는다.
 * 판을 올리지 않고 글만 고치면, 옛 글을 보고 한 동의가 새 글에 대한 동의로 남는다.
 */

export type LegalSlug = 'terms' | 'privacy';

export type LegalBlock =
  | { kind: 'paragraph'; text: string }
  | { kind: 'list'; items: readonly string[] }
  /** 이름과 값이 짝을 이루는 항목(받는 곳, 나라 등) */
  | { kind: 'facts'; rows: ReadonlyArray<readonly [label: string, value: string]> }
  /** 의료 서비스가 아니라는 고정 고지. 글자는 MedicalNotice가 갖고 있다. */
  | { kind: 'medical-notice' };

export interface LegalSection {
  /** 주소의 # 뒤에 붙는 이름. 동의 항목이 이 자리를 바로 가리킨다. */
  id: string;
  heading: string;
  blocks: readonly LegalBlock[];
}

export interface LegalDocument {
  slug: LegalSlug;
  title: string;
  /** 이 글의 판. 글을 고친 날의 날짜다. */
  version: string;
  summary: string;
  sections: readonly LegalSection[];
}

const p = (text: string): LegalBlock => ({ kind: 'paragraph', text });
const list = (...items: string[]): LegalBlock => ({ kind: 'list', items });

