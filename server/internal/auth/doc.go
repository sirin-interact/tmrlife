// Package auth는 이메일과 비밀번호로 가입하고 로그인하는 일, 그리고 세션을 맡는다.
//
// # 비밀번호
//
// 비밀번호는 argon2id로 해시해 매개변수와 함께 한 문자열로 저장한다. 매개변수를 올리면 그 뒤로 로그인에 성공한
// 사용자의 해시가 새 값으로 다시 만들어진다. 해시 하나가 수십 MiB를 쓰므로 동시에 계산하는 수에 한도를 둔다.
// 로그인이 몰려도 메모리는 정해진 만큼만 쓰고, 나머지는 줄을 선다.
//
// 해시하기 전에 비밀번호를 NFKC로 맞춘다. 한글은 같은 글자가 입력기와 운영체제에 따라
// 완성형으로도, 자모를 늘어놓은 꼴로도 들어온다. 맞추지 않으면 맥에서 정한 비밀번호로 다른 기기에서 로그인하지 못한다.
//
// # 알려주지 않는 것
//
// 로그인 실패는 이유를 가리지 않고 오류 하나(ErrInvalidCredentials)로 돌려준다. 가입된 이메일인지 알려주지 않으려는 것이다.
// 걸리는 시간으로도 알 수 없게, 없는 계정이어도 미리 만들어 둔 가짜 해시로 똑같은 계산을 한다.
//
// 가입은 예외다. 이미 가입된 이메일이면 ErrEmailTaken으로 그 사실을 알려준다. 알고서 둔 것이다.
// 가입하면 그 자리에서 로그인된 상태가 되는데, 메일을 보낼 길이 없는 동안에는 "가입됐다"와 "이미 있다"를 같은 답으로 뭉갤 방법이 없다.
// 마음 일기를 쓴다는 사실 자체가 남에게 알리고 싶지 않은 정보일 수 있으므로 가볍게 볼 틈이 아니다.
// 지금 이것을 늦추는 것은 주소별 가입 한도뿐이고, 한 사람을 겨냥해 한 번 확인해 보는 것은 한도로 막지 못한다.
// 메일을 보낼 수 있게 되면 가입은 두 경우 모두 "메일을 확인해 주세요"로 똑같이 답하고, 가입된 주소에는 다른 내용의 메일을 보낸다.
//
// # 확인하지 않은 이메일
//
// 가입은 이메일의 주인인지 확인하지 않는다. 남의 주소로 먼저 가입해 둘 수 있다는 뜻이다. 그래서 다음을 지킨다.
//   - 이메일이 확인되지 않은 계정(email_verified_at이 비어 있다)에는 메일을 보내지 않는다.
//   - 그런 계정에는 소셜 로그인의 바깥 계정을 붙이지 않는다. 붙이면 먼저 가입해 둔 사람이 제 비밀번호로 주인의 기록에 계속 들어온다.
//     붙이기를 거부하거나, 붙이기 전에 비밀번호를 비우고 LogoutAll로 세션을 모두 끊는다.
//   - 비밀번호 재설정은 LogoutAll을 부른다. 먼저 가입해 둔 사람이 살아 있는 세션을 쥐고 있을 수 있다.
//
// # 세션
//
// 세션 토큰은 무작위 32바이트다. 쿠키에는 그 값을 base64url로 적어 보내고, DB에는 SHA-256 해시만 저장한다.
// DB가 새어 나가도 그 값으로는 로그인할 수 없다.
// 세션은 두 가지 시간으로 끝난다. 로그인한 때부터 재는 전체 수명과, 마지막으로 쓴 때부터 재는 쉬는 시간의 한도다.
// 마지막으로 쓴 시각은 정해진 간격에 한 번만 DB에 다시 적는다. 요청마다 적으면 읽기만 하는 요청도 모두 쓰기가 된다.
//
// # 로그와 오류
//
// 이메일, 비밀번호, 토큰, 해시는 로그에도 오류 문구에도 넣지 않는다. 로그에는 사용자 ID와 세션 ID만 남긴다.
// 토큰은 SessionToken에 담겨 다니고, 어떤 길로 출력해도 고정 문자열만 나온다.
//
// # 시각
//
// 현재 시각은 주입받은 시계에서만 읽는다. 세션의 만료를 시험에서 가짜 시계로 며칠씩 옮겨 가며 확인한다.
