// Package diary는 끝난 대화를 그날의 일기 초안으로 옮긴다.
//
// # 재료
//
// 초안의 재료는 사용자가 한 말뿐이다. AI가 한 말은 모델에 보내지 않는다.
// 지시문으로 "AI의 말은 사실로 쓰지 말라"고 시키는 것만으로는 모자라다. 모델이 본 글은 언제든 초안에 섞여 나올 수 있다.
// 보지 못한 글은 섞일 수 없으므로, 지어낸 일이 일기에 들어가는 길 하나를 구조로 막는다.
// 그 대가로 "응", "아니"처럼 AI의 물음에 기대어야 뜻이 통하는 짧은 답은 재료가 되지 못한다. 일기는 사용자가 제 입으로 한 말에서만 나온다.
//
// # 하루에 하나
//
// 일기는 하루에 하나라서, 그날 이미 글이 있으면 새 대화의 내용은 그 뒤에 이어 붙인다.
// 이미 있는 글도 모델에 보내지 않는다. 모델은 이어 붙일 단락만 쓰고, 붙이는 일은 코드가 한다.
// 사용자가 고친 글은 모델을 거치지 않으므로 한 글자도 바뀌지 않는다. 손으로 쓴 일기가 외부로 나가는 일도 없다.
//
// # 어느 대화까지 일기에 담겼는가
//
// 대화마다 있는 진행 상태(conversations.processing_status)로 안다. 초안을 저장하는 트랜잭션에서
// 그 초안에 담은 대화를 done으로 바꾼다. done이나 failed인 대화는 다시 재료가 되지 않는다.
//
// 일기의 시각(확인한 시각, 고친 시각)과 대화가 끝난 시각을 견주는 방법은 쓰지 않는다. 두 가지가 어긋난다.
//   - 대화가 끝나고 초안이 만들어지기 전에 사용자가 예전 글을 확인하면, 그 대화는 "확인보다 먼저 끝났으니 담겼다"로 읽혀 영영 빠진다.
//   - 초안을 만드는 동안 끝난 다른 대화는 "초안보다 먼저 끝났으니 담겼다"로 읽힌다.
//
// 상태는 담은 대화마다 하나씩, 담은 초안과 함께 바뀌므로 그런 틈이 없다.
// 같은 작업이 두 번 돌아도 두 번째는 담을 대화가 없어 아무것도 하지 않는다. 글이 두 번 붙지 않는다.
//
// 같은 상태가 초안을 기다리는 쪽에게는 "끝났다"는 신호다(Finished). 대화를 끝내는 쪽은 상태를 pending으로 두고
// 같은 트랜잭션에서 작업을 등록한다(Enqueuer). 작업은 끝나면서 그 대화를 done이나 failed로 닫는다.
//
// # 만들지 않는 경우
//
// 위기 대응이 있었던 대화(대응 단계 이상의 관문 기록이 있는 대화)는 재료에서 뺀다. 그 대화의 말로는 초안을 자동으로 만들지 않는다.
// 같은 날의 다른 대화는 평소대로 담는다.
//
// # 실패
//
// 모델이 답하지 못했거나 답이 검사를 통과하지 못하면 작업 큐가 다시 시도한다. 시도를 다 쓰면 빈 초안을 남겨 사용자가 직접 쓸 수 있게 한다.
// 다시 해도 같은 결과가 나올 실패(거절된 요청, 열리지 않는 글)는 기다리지 않고 바로 그렇게 한다.
// 그날에 이미 글이 있으면 빈 초안으로 덮지 않는다. 있는 글을 그대로 둔다.
package diary
