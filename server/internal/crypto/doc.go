// Package crypto는 발화, 일기, 근거 발화, 기억, 자가 점검 응답처럼 민감한 글을 컬럼 단위로 암호화한다.
//
// # 열쇠는 두 겹이다
//
//   - 마스터 키: 설정에서 읽는 32바이트 키다. 버전 번호로 여러 개를 들고 있고 그중 하나가 활성이다.
//     DB에는 들어가지 않는다.
//   - 데이터 키: 사용자마다 하나씩 무작위로 만드는 32바이트 키다. 그 사용자의 글은 모두 이 키로 잠근다.
//     DB에는 활성 마스터 키로 감싼 꼴과 그 마스터 키의 버전만 저장한다.
//
// 둘 다 AES-256-GCM을 쓴다. 마스터 키를 바꿀 때는 글을 다시 잠그지 않고 데이터 키만 다시 감싼다(Rewrap).
//
// # 키를 지워서 글을 지운다
//
// 사용자마다 키를 따로 두는 이유는 계정 삭제다. 감싼 데이터 키가 담긴 행을 지우면
// 그 사용자의 암호문은 어디에 남아 있든 다시 열 수 없다. 이미 떠 놓은 백업 속의 암호문도 마찬가지다.
// 백업을 하나하나 찾아가 글을 지울 수는 없으니, 키를 지워서 글을 지운다.
//
// 이 성질에는 조건이 하나 있다. 그 백업에 감싼 데이터 키가 함께 들어 있으면 안 된다.
// 함께 들어 있으면 마스터 키를 가진 쪽은 백업만으로 글을 열 수 있다.
// 그래서 데이터 키 테이블은 글과 같은 장기 백업에 넣지 않거나, 따로 짧은 보관 기간으로 백업한다.
//
// # 암호문은 제자리에서만 열린다
//
// 암호문마다 테이블 이름, 컬럼 이름, 행 ID를 인증 데이터(AAD)로 묶는다.
// DB를 고칠 수 있는 쪽이 암호문을 다른 행이나 다른 컬럼으로 옮겨도 열리지 않는다.
// 데이터 키를 감쌀 때는 사용자 ID와 마스터 키 버전을 묶는다. 남의 키 행을 가져다 놓아도 풀리지 않는다.
// 행 ID가 AAD에 들어가므로 ID는 잠그기 전에 서버에서 만들어야 한다.
//
// # 저장 꼴
//
//	판 번호 1바이트 | nonce 12바이트 | GCM 출력(암호문 + 인증 태그 16바이트)
//
// 판 번호도 AAD에 들어간다. 모르는 판 번호는 열지 않고 ErrFormat으로 거부한다.
// nonce는 매번 crypto/rand에서 새로 뽑는다. 키가 사용자별이라 한 키로 잠그는 횟수가
// 무작위 nonce가 겹칠 걱정을 해야 하는 수준에 한참 못 미친다.
//
// # 쓰는 순서
//
//	가입:     ring.NewUserKey(userID) → Wrapped와 KEKVersion을 저장한다
//	읽고 쓰기: cache.Get(ctx, userID, 불러오는 함수) → Sealer.Seal / Sealer.Open
//	계정 삭제: 키 행을 지운 뒤 cache.Forget(userID)
//
// 풀린 데이터 키는 이 패키지 밖으로 나가지 않는다. 밖에서는 Sealer만 받는다.
// Sealer는 한 요청, 한 턴, 한 작업 동안만 들고 있고 다음에는 캐시에서 다시 받는다.
// 그래야 Forget과 MaxAge가 뜻을 가진다.
//
// # 메모리에 대해
//
// 데이터 키의 원본 바이트는 AES 키 일정을 만든 직후에 0으로 덮는다.
// 마스터 키는 base64에서 풀어 낸 복사본만 지운다. 바이트로 넘겨받은 것은 넘긴 쪽의 것이라 건드리지 않는다.
// 그 뒤로 키는 표준 라이브러리 안의 키 일정으로만 남는데, 이것은 밖에서 지울 수 없다.
// 캐시에서 밀려난 Sealer는 참조만 끊기고 메모리는 GC가 거둬 간다.
// Forget은 이 프로세스의 캐시만 비운다. 다른 프로세스는 MaxAge가 지나야 키를 놓는다.
//
// # 오류
//
// 오류에는 평문도 키도 들어가지 않는다. 식별자(테이블, 컬럼, 행 ID, 키 버전)와 길이만 들어간다.
