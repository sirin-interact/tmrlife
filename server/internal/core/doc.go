// Package core는 마음 신호를 숫자로 옮기는 계산을 모아 둔 곳이다.
//
// 추정 점수, 신뢰도, 개인 기준선, 변화 탐지, 개입 단계, 위기 관문의 최종 단계는
// 모두 이 아래의 순수 함수가 정한다. AI는 대화에서 신호를 뽑고 말을 만드는 일만 하고,
// 그 신호로 무엇을 할지는 여기서 정해진 식으로 계산한다.
// 그래야 같은 기록에서 언제나 같은 값이 나오고, 왜 그 값이 나왔는지 되짚을 수 있다.
//
// # 지키는 약속
//
//   - 표준 라이브러리와 기록 날짜 패키지(internal/recorddate)만 쓴다. AI, DB, 시계, 네트워크를 모른다.
//   - 현재 시각을 읽지 않는다. "언제를 기준으로 볼 것인가"는 언제나 인자로 받는다.
//     가짜 기록 몇 주 치를 한 번에 돌려 보는 시험이 이 약속에 기대고 있다.
//   - 계산 결과를 어디에도 저장하지 않는다. 사용자가 하루를 지우거나 신호 하나를 취소하면
//     남은 기록으로 처음부터 다시 계산한다. 개입 단계처럼 어제의 상태에 기대는 값도
//     첫 대화 날부터 날짜순으로 다시 돌려서 구한다. 지운 기록의 흔적이 계산에 남지 않게 하기 위해서다.
//   - 조정할 수 있는 숫자는 코드에 흩어 두지 않고 params 패키지에 모은다.
//     기본값은 초기값일 뿐이고, 가상 기록으로 돌려 본 결과를 보고 바꾼다.
//   - 전역 상태, 난수, 로그가 없다. 입력으로 받은 슬라이스를 고치지 않는다.
//
// # 하위 패키지
//
//   - signal: 여덟 항목, 판단, 명시성의 타입과 대화별 판단을 하루로 합치는 규칙
//   - score: 최근 기간의 창, 대화한 일수, 환산 일수, 항목 점수, 추정 점수와 구간, 기록 부족
//   - confidence: 기록 충실도, 항목 충족도, 근거 명시성과 이를 합친 신뢰도
//   - baseline: 개인 기준선의 기간, 하루 평균 신호 수, 항목별 관찰 비율
//   - cusum: 기준선에서 벗어난 정도를 날마다 쌓아 가는 누적값과 변화 감지 상태
//   - stage: 첫 대화 날부터 하루씩 다시 돌려 구하는 개입 단계
//   - crisis: 규칙과 AI 판별, 주변 상태를 받아 위기 관문의 최종 단계를 정하는 규칙
//   - assess: 위의 계산을 묶어 기준일의 평가와 날짜별 흐름을 돌려주는 입구.
//     끝난 하루를 돌아볼 때는 Evaluate를, 대화 도중에 상태를 읽을 때는 EvaluateLive를 쓴다
//   - params: 조정 값과 기본값
//
// 자해나 자살에 관한 표현은 여덟 항목에 들지 않는다. 점수로 쌓아 두고 기다릴 일이 아니어서
// 위기 관문이 그 자리에서 따로 다룬다.
package core
