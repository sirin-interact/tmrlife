// Package stage는 개입 단계를 정한다.
//
// 개입 단계는 사용자에게 얼마나 다가갈지를 넷으로 나눈 것이다.
// 조건을 넘었다고 곧바로 알리지 않고, 관찰을 되짚는 데서 시작해 한 단계씩 다가간다.
// 힘든 사람에게 점수와 경고는 도움보다 상처가 되기 쉽기 때문이다.
//
// # 규칙
//
// 날짜 하루의 단계는 아래 순서로 정한다. 점수의 경계와 이어진 일수는 params.Stage에서 받는다.
//
//  1. 추정 점수로 본 단계: 기본값에서 0~4는 0단계, 5~9는 1단계, 10~14는 2단계, 15 이상은 3단계다.
//  2. 변화 감지 상태면 적어도 1단계다. 점수가 낮아도 평소에서 벗어난 흐름이 이어지면 되짚어 볼 만하다.
//  3. 2단계 이상이 정해진 일수(기본 14일)째 이어지는 날부터 3단계다. 달력 날짜로 세고, 그날을 포함한다.
//     점수가 더 오르지 않아도 가볍지 않은 상태가 두 주째 이어지면 사람에게 연결하는 쪽으로 옮긴다.
//  4. 단계는 그날의 기록이 있는 날, 곧 대화한 날에만 오른다. 대화하지 않은 날에는 오르지 않는다.
//  5. 하루에 한 단계만 오른다.
//  6. 신뢰도가 낮은 날에는 전날보다 오르지 않는다. 내려가는 것은 막지 않는다.
//     적은 기록에 기대어 다가가는 것은 조심하고, 물러나는 것은 조심할 까닭이 없다.
//  7. 기록 부족인 날에는 전날의 단계를 그대로 이어 간다. 오르지도 내려가지도 않는다.
//     3번의 이어진 일수도 그날은 세지 않고 끊지도 않는다.
//  8. 창 안에 대화한 날이 하나도 없으면 0단계로 돌아가고 이어진 일수도 0이 된다. 변화 감지가 켜진 채였어도 그렇다.
//     오래 쉬었다 돌아온 사용자에게 한 달 전의 기록으로 말을 걸지 않기 위해서다.
//
// 1~3번으로 정한 단계가 Point.Raw이고, 4~7번을 거친 그날의 단계가 Point.Stage다.
// 내려가는 것은 어느 규칙도 막지 않는다(7번의 기록 부족인 날만 빼고). 몇 단계든 그날 내려간다.
//
// # 왜 이렇게 정했나
//
//   - 4번: 대화하지 않은 날에도 창은 하루 움직인다. 관찰되지 않은 날이 창에서 빠지면 대화한 일수가 줄고,
//     같은 관찰 일수가 더 큰 환산 일수가 되어 점수가 오른다. 새로 들은 말 없이 단계가 오르는 것은 맞지 않다.
//     단계에 따른 말은 어차피 대화 안에서만 전해지므로, 다음에 대화한 날에 그날의 기록까지 넣어 다시 본다.
//   - 5번: 처음부터 점수가 높은 사람도 되짚기, 제안, 권유의 순서를 거친다. 조건을 넘었다고 첫날에 곧바로 전문가를 권하지 않는다.
//     위험한 말은 이 단계와 상관없이 위기 관문이 그 자리에서 맡으므로, 천천히 다가간다고 안전이 늦어지지 않는다.
//   - 7번: 기록 부족인 날에 점수가 없다고 단계를 0으로 떨어뜨리면, 사흘 대화하고 사흘 쉬는 사람은
//     창 안의 대화한 일수가 기준을 오르내릴 때마다 단계가 3과 0을 오가고, 이어진 일수는 나흘을 넘지 못한다.
//     점수가 없는 날은 나아졌다는 근거도 나빠졌다는 근거도 없는 날이므로 전날의 판단을 그대로 둔다.
//
// # 묶인 날
//
// 4~7번 때문에 단계가 오르려던 만큼 오르지 못한 날에는 Point.Held를 켜고, 까닭을 Reasons에 적는다.
// 까닭은 하나만 적는다. 여럿이 겹치면 기록 부족, 낮은 신뢰도, 그날의 기록 없음, 하루에 한 단계의 순서로 앞선 것을 적는다.
// 앞의 둘은 기록이 더 쌓여야 풀리는 까닭이라, 단계를 올리는 대신 빠진 항목을 자연스럽게 묻거나
// 자가 점검을 제안할 근거가 된다. 뒤의 둘은 다음에 대화한 날이면 저절로 풀린다.
//
// # 첫날부터 다시 돌린다
//
// 3번부터 7번까지는 어제의 단계에 기댄다. 계산 결과를 저장해 두지 않으므로, 첫 대화 날부터 기준일까지
// 달력의 하루하루를 차례로 다시 돌려서 구한다. 사용자가 지난 하루를 지우면 그 뒤의 단계가 모두 그에 맞게 다시 정해진다.
// 대화하지 않은 날도 하루로 돌린다. 기록이 늘지 않아도 창이 하루 움직이면 대화한 일수와 점수가 달라지기 때문이다.
package stage

import (
	"strconv"

	"github.com/sirin-interact/tmrlife/server/internal/core/params"
)

// Stage는 개입 단계다.
//
// 숫자가 클수록 더 다가간다. `s >= Suggestion`처럼 견줄 수 있다.
// 빈 값은 일상이다. 채우지 않은 단계가 개입으로 읽히는 일이 없다. JSON에는 숫자(0부터 3) 그대로 적는다.
type Stage int

// 순서가 곧 크기다. 바꾸면 "전날보다 올리지 않는다"와 "2단계 이상" 같은 비교의 뜻이 달라진다.
const (
	// Everyday는 0단계, 일상이다. 대화와 일기만 제공한다.
	Everyday Stage = iota
	// Reflection은 1단계, 회고다. 관찰한 변화를 대화 안에서 부드럽게 되짚는다.
	Reflection
	// Suggestion은 2단계, 제안이다. 자가 점검을 제안하고 상담 자원을 소개한다.
	Suggestion
	// Recommendation은 3단계, 권유다. 전문가와 이야기해 보기를 분명하게 권한다.
	Recommendation
)

// Valid는 네 단계 가운데 하나인지 알려준다.
func (s Stage) Valid() bool {
	return s >= Everyday && s <= Recommendation
}

// String은 사람이 읽는 이름이다. 밖으로는 숫자로 나가므로 이 이름은 시험 출력과 디버깅에만 나온다.
func (s Stage) String() string {
	switch s {
	case Everyday:
		return "everyday"
	case Reflection:
		return "reflection"
	case Suggestion:
		return "suggestion"
	case Recommendation:
		return "recommendation"
	default:
		return "Stage(" + strconv.Itoa(int(s)) + ")"
	}
}

// FromScore는 추정 점수만으로 본 단계다. 경계는 "이 점수 이상"이다.
//
// 점수의 구간(가벼움, 중간 …)과 경계의 기본값이 같지만 따로 받는다.
// 구간은 척도를 읽는 방법이고 단계는 그 점수에서 무엇을 할지라서 따로 조정할 수 있어야 한다.
// 기록이 모자라 점수를 내지 않은 날에는 부르지 않는다. 그런 날의 0은 0점이 아니다.
func FromScore(total int, p params.Stage) Stage {
	switch {
	case total >= p.Stage3MinScore:
		return Recommendation
	case total >= p.Stage2MinScore:
		return Suggestion
	case total >= p.Stage1MinScore:
		return Reflection
	default:
		return Everyday
	}
}
