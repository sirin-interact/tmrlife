// Package engine은 대화 한 바퀴를 맡는다. 글이 들어가고 사건이 나온다.
//
// 엔진은 WebSocket도 HTTP도 모른다. 채팅 채널, 음성 파이프라인, 몇 주를 가짜 시계로 돌려 보는 실행이
// 모두 같은 엔진을 부르고, 나가는 말은 Sink로 받는다. 시각은 주입받은 시계에서만 온다.
//
// # 한 턴
//
//  1. 사용자의 말을 잠가 저장한다. 클라이언트가 붙인 식별자로 같은 글을 두 번 저장하지 않는다.
//  2. 위기 관문과 답 만들기를 동시에 시작한다. 규칙 겹은 바로 끝나고, AI 판별은 정해진 시간 안에서 기다린다.
//     그동안 만들어진 답은 버퍼에 두고 내보내지 않는다.
//  3. 두 겹이 모두 들어오면 그 사람의 최근 상태(assess.EvaluateLive)와 지난 판정(crisis.HistoryHorizon만큼)을
//     읽어 crisis.Decide로 최종 단계를 정한다.
//  4. 판정을 저장한다. 해당 없음도 저장한다. 근거 발화는 확인 단계 이상일 때만 남긴다.
//  5. 단계에 따라 내보낸다. 해당 없음이면 버퍼의 답, 확인 단계면 되묻기와 직접 묻기의 두 걸음,
//     대응 단계 이상이면 만들던 답을 취소해 버리고 미리 써 둔 말과 도움 자원을 내보낸다.
//  6. 나간 말도 출처(모델, 고정 문구, 문형)와 함께 잠가 저장한다.
//
// # 지키는 것
//
//   - 관문의 판정이 저장되기 전에는 어떤 말도 밖으로 나가지 않는다. 나가는 길은 emitReply 하나뿐이다.
//   - 대응 단계 이상에서는 버퍼의 답이 먼저 다 만들어져 있었더라도 버린다. 느리거나 실패한 대화 모델이
//     미리 써 둔 말을 늦추지도 못한다. 규칙 겹이 이미 잡은 말에는 대화 모델을 아예 부르지 않는다.
//   - 직접 묻기는 한 대화에서 한 번뿐이다. 확인 상태는 DB에 있어서 연결이 끊겼다 이어져도 유지된다.
//   - 도움 자원은 한 연결에서 한 번만 나간다. 이어붙은 연결에서는 대화를 여는 자리에서 다시 한 번 나간다.
//   - 한 턴은 컨텍스트 하나다. 그것을 취소하면 돌고 있던 모델 호출이 모두 멈춘다.
//   - 한 대화의 턴은 줄을 선다. 앞선 턴이 끝나야 다음 턴이 시작한다.
//
// # 로그
//
// 사용자의 말, 모델의 답, 근거 발화는 로그에 남기지 않는다. 식별자와 단계, 걸린 시간, 글자 수만 남긴다.
// 사건(Event)과 결과 타입은 통째로 로그에 넘겨도 내용이 나가지 않도록 LogValue를 가진다.
