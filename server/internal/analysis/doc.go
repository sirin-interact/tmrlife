// Package analysis는 끝난 대화 하나에서 여덟 항목의 마음 신호를 뽑아 저장한다.
//
// 뽑는 일만 한다. 점수, 신뢰도, 변화 탐지, 개입 단계는 신호 행을 입력으로 받는 순수 함수가 계산한다.
//
// # 여덟 항목을 한 번에
//
// 대화 하나의 결과는 여덟 항목의 행 여덟 개다. 언급이 없던 항목도 행으로 남긴다.
// 여덟 행과 "분석이 끝났다"는 표시는 한 트랜잭션에서 함께 들어가거나 하나도 들어가지 않는다.
// 절반만 들어간 대화가 생기면 그날은 "말수가 적은 날"로 보여서, 대화한 일수로 나누는 점수가 실제보다 높아진다.
//
// # 근거는 사용자가 한 말에서 글자 그대로
//
// 모델이 내놓은 근거 토막이 그 대화에서 사용자가 한 어느 한 발화의 부분 문자열이 아니면 그 항목을 버리고 언급 없음으로 되돌린다.
// 사용자와 이야기한 쪽(AI)이 한 말은 근거가 될 수 없다. 두 발화에 걸친 토막도 받지 않는다.
// 발화 하나 안에서 이어진 토막이어야 한다.
//
// 대조하기 전에 맞추는 것은 공백뿐이다. 앞뒤 공백을 떼고, 이어진 공백과 줄바꿈을 한 칸으로 줄인다.
// 모델에 보낸 글도 같은 규칙으로 줄여 보낸 것이라 모델이 본 글자와 대조하는 글자가 같다.
// 그 밖의 어떤 차이도 받아 주지 않는다. 맞춤법, 조사, 문장 부호, 같은 글자의 다른 유니코드 표기가 다르면 버린다.
// 글자와 숫자가 하나도 없는 토막(부호나 점만 있는 토막)도 버린다. 어떤 발화에나 들어 있어서 대조가 되지 않는다.
//
// 근거 행은 그 토막이 어느 발화에서 왔는지도 함께 가리킨다. 모델이 가리킨 줄이 빗나갔고 그 글자가 두 줄 이상에 있으면
// 어느 말에서 왔는지 가릴 수 없으므로, 판단과 근거는 남기고 발화만 가리키지 않는다. "응", "어" 같은 짧은 답은
// 한 대화에 여러 번 나오고 더 긴 낱말의 일부로도 걸려서, 첫 줄을 골라 두면 그 말을 하지 않은 발화에 인용이 매달린다.
//
// 이 규칙은 놓치는 쪽으로 기울어 있다. 진짜 신호였는데 모델이 한 글자를 다르게 옮기면 그 항목은 언급 없음이 된다.
// 반대 방향의 실수, 곧 기록에 없는 말이 근거로 남는 일은 이 규칙이 구조로 막는다.
// 근거는 사용자에게 그대로 보여주는 글이고, 사용자가 하지 않은 말을 근거로 내놓는 것이 가장 큰 잘못이다.
//
// 남의 말을 옮긴 것("팀장이 입맛이 없다고 해서"), 관용 표현("배고파 죽는 줄"), 비꼼, 부인은
// 글자 대조로 가릴 수 없다. 그 일은 지시문이 맡고, 실제 모델로 도는 시험이 확인한다.
//
// # 상대가 한 말은 흐름으로만 보낸다
//
// 모델에는 대화 전체를 보낸다. 사용자가 한 말에만 번호가 붙고, 상대(AI)의 말은 표시를 달아 보낸다.
// 물음을 빼면 "응", "아니", "별로" 같은 답이 무슨 뜻인지 알 수 없어서 그런 대화의 항목이 통째로 언급 없음이 된다.
//
// 일기 초안은 반대로 상대의 말을 열지도 않는다. 초안은 새로 쓰는 글이라 모델이 본 글이 그대로 섞여 나올 수 있어서,
// 보지 않은 글은 섞일 수 없다는 구조로 막는다. 여기서 나오는 것은 여덟 개의 정해진 값과 사용자의 발화에서 잘라 낸 토막뿐이고,
// 그 토막은 번호 붙은 줄과 글자로 대조한다. 그래서 상대의 말이 결과로 새는 길은 대조가 막는다.
//
// # 위기 대응이 있었던 대화도 분석한다
//
// 대응 단계 이상의 관문 기록이 있는 대화에서 일기 초안은 만들지 않지만, 신호는 뽑는다. 까닭은 셋이다.
//
//   - 신호는 새로 쓴 글이 아니다. 여덟 항목의 판단과 사용자가 제 입으로 한 말뿐이라, 힘든 순간의 사용자에게
//     시스템이 무언가를 지어내 말할 길이 없다.
//   - 그런 날은 추세에서 빠져서는 안 되는 날이다. 그 대화가 그날의 유일한 대화였으면 그날은 "대화하지 않은 날"이 되어
//     관찰된 신호가 통째로 사라지고, 점수를 나누는 대화한 일수도 하나 줄어든다. 둘 다 상태를 실제보다 가볍게 보이게 한다.
//   - 자해와 죽음에 관한 표현은 여덟 항목이 아니다. 위기 관문이 확인 단계 이상으로 판정한 발화는
//     어느 항목의 근거도 될 수 없게 코드가 막는다. "다 사라졌으면 좋겠어"는 절망감을 말한 것이기도 해서
//     지시문만으로는 막히지 않는다. 판정은 관문이 이미 내렸으므로 이 패키지는 자해 표현의 목록을 따로 들지 않는다.
//
// # 실패와 다시 하기
//
// 모델이 답하지 못했거나 답이 스키마를 따르지 않으면 작업 큐가 다시 시도한다. 시도를 다 쓰면 분석 상태를 failed로 닫고
// 행은 하나도 남기지 않는다. 절반만 남은 행은 모든 숫자를 망치는데, 행이 없는 대화는 계산에서 그냥 빠진다.
// 빠진 대화는 다음에 다시 맡을 수 있다(failed는 다시 맡는 상태다).
//
// 같은 작업을 두 번 돌려도 행이 두 번 들어가지 않는다. 이미 분석이 끝난 대화는 맡을 수 없고(ClaimConversationAnalysis),
// 맡은 뒤에 다른 실행이 먼저 저장했더라도 (대화, 항목)의 유일 제약에 걸려 한쪽만 들어간다.
// 두 번째 실행은 그것을 "이미 끝났다"로 보고 성공으로 끝난다.
//
// # 로그
//
// 발화, 근거 토막, 모델에 보낸 글은 로그에 남기지 않는다. 식별자, 항목 이름, 개수, 정해 둔 실패 이름만 남긴다.
// 다시 시도할 실패는 이 패키지가 돌려주는 오류가 작업 큐의 행에 평문으로 적히므로, 그 오류에도 정해 둔 이름만 담는다.
package analysis
